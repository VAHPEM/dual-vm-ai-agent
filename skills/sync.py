# -*- coding: utf-8 -*-
"""Copy the skills in skills/ (the single source) to where agents load them.

    python skills/sync.py                 # -> .claude/skills/ of this checkout
    python skills/sync.py --dest DIR ...  # also/instead to other skill dirs (repeatable),
                                          #    e.g. ~/.claude/skills or another project's
    python skills/sync.py --check         # report drift, change nothing (exit 1 on drift)

Each skills/<name>/ that holds a SKILL.md is copied whole to <dest>/<name>/. Edit the
markdown under skills/, never the copies: the next sync overwrites them. A copied
directory carries a marker file, so a skill deleted from skills/ is removed from <dest>
on the next sync, while skills this script did not put there are never touched.
Stdlib only; runs the same on macOS, Linux and Windows.
"""
import argparse
import filecmp
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_DEST = os.path.join(ROOT, ".claude", "skills")
MARKER = ".synced-from-labhand"
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store", MARKER)


class SyncError(Exception):
    pass


def skill_names(src=HERE):
    """Names of the skills under `src`; each must hold a SKILL.md whose front matter names it."""
    names = []
    for name in sorted(os.listdir(src)):
        path = os.path.join(src, name)
        if name.startswith((".", "_")) or not os.path.isdir(path):
            continue
        md = os.path.join(path, "SKILL.md")
        if not os.path.isfile(md):
            raise SyncError(f"{path} has no SKILL.md")
        with open(md, encoding="utf-8") as fh:
            head = fh.read(4096)
        m = re.match(r"---\r?\n(.*?)\r?\n---\r?\n", head, re.S)
        declared = re.search(r"^name:\s*(\S+)\s*$", m.group(1), re.M) if m else None
        if not declared or declared.group(1) != name:
            raise SyncError(f"{md}: front matter must start the file and say `name: {name}`")
        names.append(name)
    return names


def _files(top):
    out = set()
    for dirpath, dirnames, filenames in os.walk(top):
        dirnames[:] = [d for d in dirnames if d != "__pycache__"]
        for f in filenames:
            if f in (MARKER, ".DS_Store") or f.endswith(".pyc"):
                continue
            out.add(os.path.relpath(os.path.join(dirpath, f), top))
    return out


def drift(dest, src=HERE):
    """What a sync would change in `dest`, as human-readable lines (empty: in sync)."""
    lines = []
    names = skill_names(src)
    for name in names:
        s, d = os.path.join(src, name), os.path.join(dest, name)
        if not os.path.isdir(d):
            lines.append(f"missing: {d}")
            continue
        fs, fd = _files(s), _files(d)
        lines += [f"missing: {os.path.join(d, f)}" for f in sorted(fs - fd)]
        lines += [f"extra:   {os.path.join(d, f)}" for f in sorted(fd - fs)]
        lines += [f"differs: {os.path.join(d, f)}" for f in sorted(fs & fd)
                  if not filecmp.cmp(os.path.join(s, f), os.path.join(d, f), shallow=False)]
    for name in _stale(dest, names):
        lines.append(f"stale:   {os.path.join(dest, name)} (no longer in skills/)")
    return lines


def _stale(dest, names):
    if not os.path.isdir(dest):
        return []
    return [n for n in sorted(os.listdir(dest))
            if n not in names and os.path.isfile(os.path.join(dest, n, MARKER))]


def sync(dest, src=HERE):
    """Copy every skill to `dest`; returns the names written and the stale names removed."""
    names = skill_names(src)
    os.makedirs(dest, exist_ok=True)
    for name in names:
        target = os.path.join(dest, name)
        if os.path.isdir(target) and not os.path.isfile(os.path.join(target, MARKER)) \
                and _files(target) - _files(os.path.join(src, name)):
            # A same-named skill someone else put there, with files we do not own: refuse
            # rather than delete them.
            raise SyncError(f"{target} exists, was not written by this script and holds other "
                            "files; move it away first")
        tmp = os.path.join(dest, f".{name}.sync-tmp")
        shutil.rmtree(tmp, ignore_errors=True)
        try:
            shutil.copytree(os.path.join(src, name), tmp, ignore=IGNORE)
            with open(os.path.join(tmp, MARKER), "w", encoding="utf-8") as fh:
                fh.write("Generated by skills/sync.py from skills/%s/ - edit the source there.\n" % name)
            if os.path.isdir(target):
                shutil.rmtree(target)
            os.replace(tmp, target)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
    stale = _stale(dest, names)
    for name in stale:
        shutil.rmtree(os.path.join(dest, name))
    return names, stale


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dest", action="append",
                    help=f"skill directory to write (repeatable; default {DEFAULT_DEST})")
    ap.add_argument("--check", action="store_true", help="only report drift; exit 1 if any")
    a = ap.parse_args(argv)
    dests = [os.path.abspath(os.path.expanduser(d)) for d in (a.dest or [DEFAULT_DEST])]
    rc = 0
    try:
        for dest in dests:
            if a.check:
                lines = drift(dest)
                print(f"{dest}: " + ("in sync" if not lines else f"{len(lines)} difference(s)"))
                for line in lines:
                    print("  " + line)
                rc |= bool(lines)
            else:
                names, stale = sync(dest)
                print(f"{dest}: wrote {', '.join(names) or 'nothing'}"
                      + (f"; removed stale {', '.join(stale)}" if stale else ""))
    except SyncError as e:
        print(f"skills/sync.py: {e}", file=sys.stderr)
        return 2
    return rc


if __name__ == "__main__":
    sys.exit(main())
